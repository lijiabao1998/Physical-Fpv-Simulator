"""System identification: model parameters from test data.

Each fit is ordinary least squares on a model that is linear in its
parameters. Standard errors use the HC3 heteroscedasticity-consistent
covariance (MacKinnon & White, 1985), because test-stand noise usually grows
with the reading (load cells, current shunts) and the classic s^2 (A^T A)^-1
would then understate the uncertainty. Measured parameters thus enter the
design with an honest uncertainty.

Test data is CSV with "name [unit]" headers, e.g. "thrust [gf]"; units are
converted to SI on read.
"""

from __future__ import annotations

import csv
import math
import re
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from . import units

_HEADER = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*\[([^\]]+)\]\s*$")


SYNTHETIC_MARK = "fpvsim synthetic data"


def synthetic_marker(what: str) -> str:
    """First line of a CSV written by a virtual instrument, so analyses can tell it from a measurement."""
    return f"# {SYNTHETIC_MARK}: {what}; generated by the model, not a measurement\n"


def is_synthetic(notes: list[str]) -> bool:
    return any(SYNTHETIC_MARK in n for n in notes)


def read_csv(path: str | Path) -> dict[str, np.ndarray]:
    """Read a test-data CSV into SI arrays keyed by column name."""
    return read_csv_notes(path)[0]


def read_csv_notes(path: str | Path) -> tuple[dict[str, np.ndarray], list[str]]:
    """Like read_csv, also returning the comment lines ('# ...') before the header."""
    notes = []
    with Path(path).open(newline="") as f:
        pos = f.tell()
        line = f.readline()
        while line.startswith("#"):
            notes.append(line[1:].strip())
            pos = f.tell()
            line = f.readline()
        f.seek(pos)
        reader = csv.reader(f)
        header = next(reader)
        columns = []
        for cell in header:
            match = _HEADER.match(cell)
            if not match:
                raise ValueError(f"{path}: column {cell!r} must look like 'name [unit]'")
            columns.append((match.group(1), match.group(2)))
        rows = [[float(x) for x in row] for row in reader if row]
    data = np.array(rows, dtype=float)
    return {name: np.array([units.to_si(v, unit) for v in data[:, i]]) for i, (name, unit) in enumerate(columns)}, notes


@dataclass(frozen=True)
class Fit:
    values: dict[str, float]
    stderr: dict[str, float]
    n: int
    residual_rms: float
    r2: float

    def u_rel(self, key: str) -> float:
        return self.stderr[key] / abs(self.values[key])


def _ols(A: np.ndarray, y: np.ndarray, names: tuple[str, ...]) -> Fit:
    n, k = A.shape
    if n <= k:
        raise ValueError(f"need more than {k} data points, got {n}")
    beta, *_ = np.linalg.lstsq(A, y, rcond=None)
    resid = y - A @ beta
    bread = np.linalg.inv(A.T @ A)
    leverage = np.einsum("ij,jk,ik->i", A, bread, A)
    meat = (A * (resid / (1.0 - leverage))[:, None] ** 2).T @ A
    cov = bread @ meat @ bread  # HC3 sandwich estimator
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    r2 = 1.0 - float(resid @ resid) / ss_tot if ss_tot > 0 else 1.0
    return Fit(
        values=dict(zip(names, map(float, beta))),
        stderr=dict(zip(names, map(float, np.sqrt(np.diag(cov))))),
        n=n,
        residual_rms=math.sqrt(float(resid @ resid) / n),
        r2=r2,
    )


def fit_prop_static(omega: np.ndarray, thrust: np.ndarray, torque: np.ndarray, rho: float, diameter: float) -> dict[str, Fit]:
    """Static Ct and Cp from rpm, thrust and torque (T = kT w^2, Q = kQ w^2)."""
    mask = omega > 0
    w2 = omega[mask] ** 2
    fits = {"thrust": _ols(w2[:, None], thrust[mask], ("k",)), "torque": _ols(w2[:, None], torque[mask], ("k",))}
    to_ct = (2.0 * math.pi) ** 2 / (rho * diameter**4)
    to_cp = (2.0 * math.pi) ** 3 / (rho * diameter**5)  # Cp = 2 pi Cq
    out = {}
    for name, fit, factor in (("ct0", fits["thrust"], to_ct), ("cp0", fits["torque"], to_cp)):
        out[name] = Fit(
            values={name: fit.values["k"] * factor},
            stderr={name: fit.stderr["k"] * factor},
            n=fit.n,
            residual_rms=fit.residual_rms,
            r2=fit.r2,
        )
    return out


LACK_OF_FIT = 0.01  # residual RMS of log Ct or log FM above which the power law does not describe the data


def fit_prop_reynolds(omega: np.ndarray, thrust: np.ndarray, torque: np.ndarray, rho: float, nu: float,
                      diameter: float, chord75: float, re_range: tuple[float, float] | None = None) -> dict:
    """Static Ct, Cp and figure of merit as power laws of the blade Reynolds number
    Re75 = omega (0.75 R) c75 / nu (prop.ReynoldsCorrection), by least squares
    in log-log: log Ct = log Ct_ref + n_T log(Re / Re_ref), the same for FM and Cp.
    Re_ref is the geometric mean of the data's Re, so the levels and exponents
    are nearly uncorrelated. Points with zero speed, thrust or torque, and with
    ``re_range`` given, points outside it, are left out. ``lack_of_fit`` is True
    when the residuals are larger than LACK_OF_FIT (1 %): the coefficients do not
    follow one power law over the data (they may level off at its ends), and
    ``re_range`` should narrow the fit."""
    mask = (omega > 0) & (thrust > 0) & (torque > 0)
    re_all = omega * 0.75 * 0.5 * diameter * chord75 / nu
    if re_range is not None:
        mask &= (re_all >= re_range[0]) & (re_all <= re_range[1])
    w, t, q, re = omega[mask], thrust[mask], torque[mask], re_all[mask]
    n = w / (2.0 * math.pi)
    ct = t / (rho * n**2 * diameter**4)
    cp = 2.0 * math.pi * q / (rho * n**2 * diameter**5)
    fm = ct**1.5 * math.sqrt(2.0 / math.pi) / cp
    re_ref = float(math.exp(np.mean(np.log(re))))
    A = np.column_stack([np.ones_like(re), np.log(re / re_ref)])
    fits = {key: _ols(A, np.log(y), ("log_ref", "exponent")) for key, y in (("ct", ct), ("fm", fm), ("cp", cp))}
    ct_ref, fm_ref = math.exp(fits["ct"].values["log_ref"]), math.exp(fits["fm"].values["log_ref"])
    return {
        "re_ref": re_ref, "re_min": float(re.min()), "re_max": float(re.max()), "n": int(mask.sum()),
        "ct_ref": ct_ref, "fm_ref": fm_ref, "cp_ref": ct_ref**1.5 * math.sqrt(2.0 / math.pi) / fm_ref,
        "fits": fits,
        "lack_of_fit": max(fits["ct"].residual_rms, fits["fm"].residual_rms) > LACK_OF_FIT,
    }


def fit_motor_no_load(voltage: np.ndarray, current: np.ndarray, omega: np.ndarray, rm: float) -> dict[str, Fit]:
    """Kv and the affine no-load current model from a no-load (no prop) sweep.

    Back-EMF: V - I Rm = Ke w  (through the origin)  ->  Kv = 1 / Ke
    Losses:   I0 = a + b w
    Rm must be measured separately (four-wire resistance measurement).
    """
    emf = _ols(omega[:, None], voltage - current * rm, ("ke",))
    ke = emf.values["ke"]
    kv = Fit({"kv": 1.0 / ke}, {"kv": emf.stderr["ke"] / ke**2}, emf.n, emf.residual_rms, emf.r2)
    losses = _ols(np.column_stack([np.ones_like(omega), omega]), current, ("i0_const", "i0_slope"))
    return {"kv": kv, "i0": losses}


def fit_motor_loaded(v_motor: np.ndarray, i_motor: np.ndarray, omega: np.ndarray) -> Fit:
    """Ke and circuit resistance from loaded points: V = Ke w + R I."""
    return _ols(np.column_stack([omega, i_motor]), v_motor, ("ke", "r_circuit"))
